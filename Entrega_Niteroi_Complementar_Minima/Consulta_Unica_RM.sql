WITH T AS (
SELECT * FROM dbo.STURMA WHERE CODCOLIGADA=3 AND CODFILIAL=266 AND DTFINAL>=CONVERT(date,'20270101',112)
AND CODTURMA IN (N'QUA00262026U040',N'QUA01082026U121',N'QUA05172026U001',N'QUA05172026U002',N'QUA05172026U003',N'QUA05172026U004',N'QUA05182026U009',N'QUA05182026U011',N'QUA05192026U001',N'QUA05192026U002',N'QUA05202026U001',N'QUA05212026U001',N'QUA05212026U002',N'QUA05222026U001',N'QUA05222026U002',N'QUA05242026U001',N'QUA05252026U001',N'QUA05282026U001',N'QUA05282026U002',N'QUA05292026U001',N'QUA05302026U001',N'QUA05302026U002',N'QUA05312026U001',N'QUA05312026U002',N'TEC00082026.2001',N'TEC00152026.2001',N'TEC00482026.2001',N'TEC00782026.2001',N'TEC01702026.2001',N'TEC01712026.2002',N'TEC01752026.2001')
), X AS (
SELECT C.CODCOLIGADA,C.CODFILIAL,C.IDPERLET,C.CODTURMA,COUNT(*) N,
CASE WHEN COUNT(*)=1 THEN MAX(CONVERT(nvarchar(100),C.CLASSIFICACAO)) END Classificacao,
CASE WHEN COUNT(*)=1 THEN MAX(CONVERT(nvarchar(100),C.MOBILIZACAO)) END Mobilizacao
FROM dbo.STURMACOMPL C INNER JOIN T ON T.CODCOLIGADA=C.CODCOLIGADA AND T.CODFILIAL=C.CODFILIAL AND T.IDPERLET=C.IDPERLET AND T.CODTURMA=C.CODTURMA
GROUP BY C.CODCOLIGADA,C.CODFILIAL,C.IDPERLET,C.CODTURMA
), MOB AS (
SELECT CONVERT(nvarchar(100),CODCLIENTE) Codigo,COUNT(*) N,
CASE WHEN COUNT(*)=1 THEN MAX(CONVERT(nvarchar(4000),DESCRICAO)) END Descricao
FROM dbo.GCONSIST WHERE CODCOLIGADA=3 AND APLICACAO='S' AND CODTABELA='POMOBILIZA'
GROUP BY CONVERT(nvarchar(100),CODCLIENTE)
)
SELECT T.CODCOLIGADA,T.CODFILIAL,T.IDPERLET,CONVERT(nvarchar(100),T.CODTURMA) Codigo_Turma,
CONVERT(nvarchar(100),H.CODCURSO) Codigo_Curso,CONVERT(nvarchar(100),H.CODHABILITACAO) Codigo_Habilitacao,
CONVERT(nvarchar(100),H.CODGRADE) Codigo_Matriz,
CONVERT(nvarchar(100),P.CODPERLET) Periodo_Letivo,T.DTINICIAL Data_Inicio,T.DTFINAL Data_Fim,T.MAXALUNOS Vagas,
CONVERT(nvarchar(100),T.CODCAMPUS) Codigo_Campus,CONVERT(nvarchar(100),T.TIPOMEDIACAO) Codigo_Mediacao,
X.N Ocorrencias_Complemento,X.Classificacao,X.Mobilizacao Codigo_Mobilizacao,MOB.N Ocorrencias_Mobilizacao,MOB.Descricao Descricao_Mobilizacao
FROM T LEFT JOIN dbo.SHABILITACAOFILIAL H ON H.CODCOLIGADA=T.CODCOLIGADA AND H.IDHABILITACAOFILIAL=T.IDHABILITACAOFILIAL
LEFT JOIN dbo.SPLETIVO P ON P.CODCOLIGADA=T.CODCOLIGADA AND P.IDPERLET=T.IDPERLET
LEFT JOIN X ON X.CODCOLIGADA=T.CODCOLIGADA AND X.CODFILIAL=T.CODFILIAL AND X.IDPERLET=T.IDPERLET AND X.CODTURMA=T.CODTURMA
LEFT JOIN MOB ON MOB.Codigo=X.Mobilizacao
ORDER BY T.CODTURMA;