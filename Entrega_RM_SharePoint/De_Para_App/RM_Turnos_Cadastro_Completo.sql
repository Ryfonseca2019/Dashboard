SELECT CODCOLIGADA,CODFILIAL,CODTIPOCURSO,
CONVERT(nvarchar(100),CODTURNO) Codigo_Turno,
CONVERT(nvarchar(4000),NOME) Nome_Turno,
CONVERT(nvarchar(100),TIPO) Tipo_Turno,
CONVERT(nvarchar(100),HORINI) Hora_Inicio,
CONVERT(nvarchar(100),HORFIM) Hora_Fim
FROM dbo.STURNO WHERE CODCOLIGADA=3
ORDER BY CODFILIAL,CODTIPOCURSO,CODTURNO;