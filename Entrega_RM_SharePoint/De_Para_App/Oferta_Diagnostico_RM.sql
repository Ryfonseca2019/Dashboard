-- Somente SENAI, término no ano atual em diante. Diagnóstico, sem tradução presumida de códigos.
SELECT T.CODCOLIGADA AS RM_CODCOLIGADA, T.CODFILIAL AS RM_CODFILIAL,
    T.IDPERLET AS RM_IDPERLET, T.CODTURMA AS RM_CODTURMA,
    H.CODCURSO AS RM_Codigo_Curso, H.CODGRADE AS RM_Codigo_Grade,
    H.CODHABILITACAO AS RM_Codigo_Habilitacao,
    H.CODTURNO AS RM_Codigo_Turno, H.CODTIPOCURSO AS RM_Tipo_Curso,
    G.N AS Ocorrencias_Grade, G.Carga AS RM_Carga_Horaria,
    G.Descricao AS RM_Descricao_Grade,
    U.N AS Ocorrencias_Turno, U.Nome AS RM_Nome_Turno,
    T.TIPOMEDIACAO AS RM_Tipo_Mediacao,
    T.MODALIDADE AS RM_Modalidade_Turma,
    C.CODMODALIDADECURSO AS RM_Codigo_Modalidade,
    M.N AS Ocorrencias_Modalidade, M.Descricao AS RM_Descricao_Modalidade,
    X.N AS Ocorrencias_Complemento, X.Turno AS RM_Turno_Complemento,
    X.Oferta AS RM_OFERTAP, X.Plano AS RM_PLANO,
    X.Classificacao AS RM_CLASSIFICACAO, X.Programa AS RM_PROGTURMA,
    X.Mobilizacao AS RM_MOBILIZACAO
FROM dbo.STURMA T
LEFT JOIN dbo.SHABILITACAOFILIAL H
    ON H.CODCOLIGADA=T.CODCOLIGADA AND H.IDHABILITACAOFILIAL=T.IDHABILITACAOFILIAL
LEFT JOIN dbo.SCURSO C ON C.CODCOLIGADA=H.CODCOLIGADA AND C.CODCURSO=H.CODCURSO
OUTER APPLY (
    SELECT COUNT(*) N,
        CASE WHEN COUNT(*)=1 THEN MAX(GR.CARGAHORARIA) END Carga,
        CASE WHEN COUNT(*)=1 THEN MAX(GR.DESCRICAO) END Descricao
    FROM dbo.SGRADE GR
    WHERE GR.CODCOLIGADA=H.CODCOLIGADA AND GR.CODCURSO=H.CODCURSO
        AND GR.CODHABILITACAO=H.CODHABILITACAO AND GR.CODGRADE=H.CODGRADE
) G
OUTER APPLY (
    SELECT COUNT(*) N, CASE WHEN COUNT(*)=1 THEN MAX(TU.NOME) END Nome
    FROM dbo.STURNO TU
    WHERE TU.CODCOLIGADA=H.CODCOLIGADA AND TU.CODFILIAL=H.CODFILIAL
        AND TU.CODTIPOCURSO=H.CODTIPOCURSO AND TU.CODTURNO=H.CODTURNO
) U
OUTER APPLY (
    SELECT COUNT(*) N, CASE WHEN COUNT(*)=1 THEN MAX(MO.DESCRICAO) END Descricao
    FROM dbo.SMODALIDADECURSO MO
    WHERE MO.CODCOLIGADA=C.CODCOLIGADA AND MO.CODMODALIDADECURSO=C.CODMODALIDADECURSO
) M
OUTER APPLY (
    SELECT COUNT(*) N,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.TURNO) END Turno,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.OFERTAP) END Oferta,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.PLANO) END Plano,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.CLASSIFICACAO) END Classificacao,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.PROGTURMA) END Programa,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.MOBILIZACAO) END Mobilizacao
    FROM dbo.STURMACOMPL TC
    WHERE TC.CODCOLIGADA=T.CODCOLIGADA AND TC.CODFILIAL=T.CODFILIAL
        AND TC.IDPERLET=T.IDPERLET AND TC.CODTURMA=T.CODTURMA
) X
WHERE T.CODCOLIGADA=3 AND T.DTFINAL>=DATEFROMPARTS(YEAR(GETDATE()),1,1);
