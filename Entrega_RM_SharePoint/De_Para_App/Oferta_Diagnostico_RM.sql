-- Somente SENAI, término no ano atual em diante.
-- Agrega cada cadastro por chave antes do join, em vez de OUTER APPLY por turma.
WITH Turmas AS (
    SELECT * FROM dbo.STURMA
    WHERE CODCOLIGADA=3 AND DTFINAL>=DATEFROMPARTS(YEAR(GETDATE()),1,1)
), G AS (
    SELECT CODCOLIGADA,CODCURSO,CODHABILITACAO,CODGRADE,COUNT(*) N,
        CASE WHEN COUNT(*)=1 THEN MAX(CARGAHORARIA) END Carga,
        CASE WHEN COUNT(*)=1 THEN MAX(DESCRICAO) END Descricao
    FROM dbo.SGRADE WHERE CODCOLIGADA=3
    GROUP BY CODCOLIGADA,CODCURSO,CODHABILITACAO,CODGRADE
), U AS (
    SELECT CODCOLIGADA,CODFILIAL,CODTIPOCURSO,CODTURNO,COUNT(*) N,
        CASE WHEN COUNT(*)=1 THEN MAX(NOME) END Nome
    FROM dbo.STURNO WHERE CODCOLIGADA=3
    GROUP BY CODCOLIGADA,CODFILIAL,CODTIPOCURSO,CODTURNO
), M AS (
    SELECT CODCOLIGADA,CODMODALIDADECURSO,COUNT(*) N,
        CASE WHEN COUNT(*)=1 THEN MAX(DESCRICAO) END Descricao
    FROM dbo.SMODALIDADECURSO WHERE CODCOLIGADA=3
    GROUP BY CODCOLIGADA,CODMODALIDADECURSO
), X AS (
    SELECT TC.CODCOLIGADA,TC.CODFILIAL,TC.IDPERLET,TC.CODTURMA,COUNT(*) N,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.TURNO) END Turno,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.OFERTAP) END Oferta,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.PLANO) END Plano,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.CLASSIFICACAO) END Classificacao,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.PROGTURMA) END Programa,
        CASE WHEN COUNT(*)=1 THEN MAX(TC.MOBILIZACAO) END Mobilizacao
    FROM dbo.STURMACOMPL TC
    WHERE TC.CODCOLIGADA=3 AND EXISTS (
        SELECT 1 FROM Turmas T
        WHERE T.CODCOLIGADA=TC.CODCOLIGADA AND T.CODFILIAL=TC.CODFILIAL
            AND T.IDPERLET=TC.IDPERLET AND T.CODTURMA=TC.CODTURMA)
    GROUP BY TC.CODCOLIGADA,TC.CODFILIAL,TC.IDPERLET,TC.CODTURMA
)
SELECT T.CODCOLIGADA AS RM_CODCOLIGADA, T.CODFILIAL AS RM_CODFILIAL,
    T.IDPERLET AS RM_IDPERLET, T.CODTURMA AS RM_CODTURMA,
    H.CODCURSO AS RM_Codigo_Curso, H.CODGRADE AS RM_Codigo_Grade,
    H.CODHABILITACAO AS RM_Codigo_Habilitacao,
    H.CODTURNO AS RM_Codigo_Turno, H.CODTIPOCURSO AS RM_Tipo_Curso,
    COALESCE(G.N,0) AS Ocorrencias_Grade, G.Carga AS RM_Carga_Horaria,
    G.Descricao AS RM_Descricao_Grade,
    COALESCE(U.N,0) AS Ocorrencias_Turno, U.Nome AS RM_Nome_Turno,
    T.TIPOMEDIACAO AS RM_Tipo_Mediacao,
    T.MODALIDADE AS RM_Modalidade_Turma,
    C.CODMODALIDADECURSO AS RM_Codigo_Modalidade,
    COALESCE(M.N,0) AS Ocorrencias_Modalidade, M.Descricao AS RM_Descricao_Modalidade,
    COALESCE(X.N,0) AS Ocorrencias_Complemento, X.Turno AS RM_Turno_Complemento,
    X.Oferta AS RM_OFERTAP, X.Plano AS RM_PLANO,
    X.Classificacao AS RM_CLASSIFICACAO, X.Programa AS RM_PROGTURMA,
    X.Mobilizacao AS RM_MOBILIZACAO
FROM Turmas T
LEFT JOIN dbo.SHABILITACAOFILIAL H
    ON H.CODCOLIGADA=T.CODCOLIGADA AND H.IDHABILITACAOFILIAL=T.IDHABILITACAOFILIAL
LEFT JOIN dbo.SCURSO C ON C.CODCOLIGADA=H.CODCOLIGADA AND C.CODCURSO=H.CODCURSO
LEFT JOIN G ON G.CODCOLIGADA=H.CODCOLIGADA AND G.CODCURSO=H.CODCURSO
    AND G.CODHABILITACAO=H.CODHABILITACAO AND G.CODGRADE=H.CODGRADE
LEFT JOIN U ON U.CODCOLIGADA=H.CODCOLIGADA AND U.CODFILIAL=H.CODFILIAL
    AND U.CODTIPOCURSO=H.CODTIPOCURSO AND U.CODTURNO=H.CODTURNO
LEFT JOIN M ON M.CODCOLIGADA=C.CODCOLIGADA AND M.CODMODALIDADECURSO=C.CODMODALIDADECURSO
LEFT JOIN X ON X.CODCOLIGADA=T.CODCOLIGADA AND X.CODFILIAL=T.CODFILIAL
    AND X.IDPERLET=T.IDPERLET AND X.CODTURMA=T.CODTURMA;
