WITH C AS (
 SELECT CODCOLIGADA,CODCURSO,COUNT(*) N,
 CASE WHEN COUNT(*)=1 THEN MAX(NOME) END Nome,
 CASE WHEN COUNT(*)=1 THEN MAX(CONVERT(nvarchar(100),CODMODALIDADECURSO)) END CodigoModalidade
 FROM dbo.SCURSO WHERE CODCOLIGADA=3 GROUP BY CODCOLIGADA,CODCURSO
), M AS (
 SELECT CODCOLIGADA,CONVERT(nvarchar(100),CODMODALIDADECURSO) Codigo,COUNT(*) N,
 CASE WHEN COUNT(*)=1 THEN MAX(DESCRICAO) END Nome
 FROM dbo.SMODALIDADECURSO WHERE CODCOLIGADA=3 GROUP BY CODCOLIGADA,CONVERT(nvarchar(100),CODMODALIDADECURSO)
), X AS (
 SELECT CODCOLIGADA,CODCURSO,CODHABILITACAO,CODGRADE,COUNT(*) N,
 CASE WHEN COUNT(*)=1 THEN MAX(CONVERT(nvarchar(100),TIPOEAD)) END CodigoEAD
 FROM dbo.SGRADECOMPL WHERE CODCOLIGADA=3 GROUP BY CODCOLIGADA,CODCURSO,CODHABILITACAO,CODGRADE
), E AS (
 SELECT CONVERT(nvarchar(100),CODCLIENTE) Codigo,COUNT(*) N,
 CASE WHEN COUNT(*)=1 THEN MAX(DESCRICAO) END Nome
 FROM dbo.GCONSIST WHERE CODCOLIGADA=3 AND APLICACAO='S' AND CODTABELA='TIPOEAD'
 GROUP BY CONVERT(nvarchar(100),CODCLIENTE)
)
SELECT G.CODCOLIGADA,
CONVERT(nvarchar(100),G.CODCURSO) Codigo_Curso_RM,
CONVERT(nvarchar(100),G.CODHABILITACAO) Codigo_Habilitacao_RM,
CONVERT(nvarchar(100),G.CODGRADE) Codigo_Matriz_RM,
G.DESCRICAO Descricao_Matriz_RM,G.CARGAHORARIA Carga_Horaria_RM,
CONVERT(nvarchar(100),G.STATUS) Status_Matriz_RM,
C.N Ocorrencias_Curso,C.Nome Nome_Curso_RM,C.CodigoModalidade Codigo_Modalidade_RM,
M.N Ocorrencias_Modalidade,M.Nome Modalidade_RM,
X.N Ocorrencias_Complemento,X.CodigoEAD Codigo_Tipo_EAD_RM,
E.N Ocorrencias_Dominio_EAD,E.Nome Tipo_EAD_RM
FROM dbo.SGRADE G
LEFT JOIN C ON C.CODCOLIGADA=G.CODCOLIGADA AND C.CODCURSO=G.CODCURSO
LEFT JOIN M ON M.CODCOLIGADA=G.CODCOLIGADA AND M.Codigo=C.CodigoModalidade
LEFT JOIN X ON X.CODCOLIGADA=G.CODCOLIGADA AND X.CODCURSO=G.CODCURSO AND X.CODHABILITACAO=G.CODHABILITACAO AND X.CODGRADE=G.CODGRADE
LEFT JOIN E ON E.Codigo=X.CodigoEAD
WHERE G.CODCOLIGADA=3
ORDER BY G.CODCURSO,G.CODHABILITACAO,G.CODGRADE;