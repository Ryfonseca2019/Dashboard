WITH D AS (
 SELECT ENTIDADE,COD_UNIDADE,IDPERLET,TURMA,
 CONVERT(nvarchar(4000),MEDIACAO) Descricao,
 COUNT_BIG(*) Ocorrencias,MAX(DATA_EMISSAO) UltimaEmissao
 FROM dbo.tmpDashsSGE WHERE ENTIDADE=3
 GROUP BY ENTIDADE,COD_UNIDADE,IDPERLET,TURMA,CONVERT(nvarchar(4000),MEDIACAO)
)
SELECT T.CODCOLIGADA,T.CODFILIAL,T.IDPERLET,
CONVERT(nvarchar(100),T.CODTURMA) CODTURMA,
CONVERT(nvarchar(100),T.TIPOMEDIACAO) Codigo_Mediacao,
D.Descricao Descricao_Auxiliar,D.Ocorrencias Ocorrencias_Auxiliar,
D.UltimaEmissao Ultima_Emissao_Auxiliar,
CASE WHEN D.Ocorrencias IS NULL THEN N'Sem correspondência auxiliar pela chave candidata' ELSE N'Evidência auxiliar; validar significado e atualidade' END Status_Evidencia
FROM dbo.STURMA T LEFT JOIN D ON D.ENTIDADE=T.CODCOLIGADA AND D.COD_UNIDADE=T.CODFILIAL AND D.IDPERLET=T.IDPERLET AND D.TURMA=T.CODTURMA
WHERE T.CODCOLIGADA=3 AND T.CODFILIAL=266
AND T.DTFINAL>=CONVERT(date,'20270101',112)
ORDER BY T.TIPOMEDIACAO,T.CODTURMA;