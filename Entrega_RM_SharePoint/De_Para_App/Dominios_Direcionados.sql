SELECT CODCOLIGADA, APLICACAO,
    CONVERT(nvarchar(4000),CODTABELA) AS Codigo_Tabela,
    CONVERT(nvarchar(4000),CODCLIENTE) AS Codigo_Valor,
    CONVERT(nvarchar(4000),DESCRICAO) AS Descricao_Valor
FROM dbo.GCONSIST
WHERE (CODCOLIGADA=0 AND CODTABELA='CLASSIFTUR')
   OR (CODCOLIGADA=3 AND CODTABELA='TIPOTURNO');