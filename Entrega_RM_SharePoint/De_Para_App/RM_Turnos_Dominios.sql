SELECT CODCOLIGADA, CONVERT(nvarchar(100),APLICACAO) APLICACAO,
CONVERT(nvarchar(4000),CODTABELA) Codigo_Tabela,CONVERT(nvarchar(4000),CODCLIENTE) Codigo_Valor,CONVERT(nvarchar(4000),DESCRICAO) Descricao_Valor
FROM dbo.GCONSIST WHERE CODCOLIGADA IN(0,3) AND (
CONVERT(nvarchar(4000),CODTABELA) COLLATE Latin1_General_CI_AI LIKE '%TURNO%'
OR LTRIM(RTRIM(CONVERT(nvarchar(4000),DESCRICAO))) COLLATE Latin1_General_CI_AI IN ('MANHA','TARDE','NOITE','INTEGRAL','MATUTINO','VESPERTINO','NOTURNO'))
ORDER BY CODCOLIGADA,APLICACAO,CODTABELA,CODCLIENTE;