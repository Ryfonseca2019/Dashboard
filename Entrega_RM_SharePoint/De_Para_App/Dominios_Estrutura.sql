SELECT TABLE_SCHEMA,TABLE_NAME,COLUMN_NAME,DATA_TYPE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE UPPER(TABLE_NAME) LIKE '%CONSIST%'
 OR UPPER(TABLE_NAME) LIKE '%CAMP%COMPL%'
 OR UPPER(TABLE_NAME) LIKE '%FINANC%'
 OR UPPER(TABLE_NAME) IN ('GCAMPOS','GCOLUNAS','GCAMPOSCOMPL','GCAMPOSCOMPLEMENTARES')
ORDER BY TABLE_SCHEMA,TABLE_NAME,ORDINAL_POSITION;