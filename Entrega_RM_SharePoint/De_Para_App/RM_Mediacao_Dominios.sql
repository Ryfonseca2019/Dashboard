SELECT CODCOLIGADA, CONVERT(nvarchar(100),APLICACAO) APLICACAO,
CONVERT(nvarchar(4000),CODTABELA) Codigo_Tabela,
CONVERT(nvarchar(4000),CODCLIENTE) Codigo_Valor,
CONVERT(nvarchar(4000),DESCRICAO) Descricao_Valor
FROM dbo.GCONSIST
WHERE CODCOLIGADA IN (0,3) AND (
 CONVERT(nvarchar(4000),CODTABELA) COLLATE Latin1_General_CI_AI LIKE '%MEDI%'
 OR CONVERT(nvarchar(4000),CODTABELA) COLLATE Latin1_General_CI_AI LIKE '%MODAL%'
 OR CONVERT(nvarchar(4000),DESCRICAO) COLLATE Latin1_General_CI_AI LIKE '%PRESENC%'
 OR CONVERT(nvarchar(4000),DESCRICAO) COLLATE Latin1_General_CI_AI LIKE '%DISTANC%'
 OR CONVERT(nvarchar(4000),DESCRICAO) COLLATE Latin1_General_CI_AI LIKE '%HIBRID%'
 OR CONVERT(nvarchar(4000),DESCRICAO) COLLATE Latin1_General_CI_AI LIKE '%MEDIAC%')
ORDER BY CODCOLIGADA,CODTABELA,CODCLIENTE;