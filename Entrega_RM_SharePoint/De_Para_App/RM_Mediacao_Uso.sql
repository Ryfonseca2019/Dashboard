SELECT T.CODCOLIGADA,T.CODFILIAL,
CONVERT(nvarchar(100),T.TIPOMEDIACAO) Codigo_Mediacao,
COUNT_BIG(*) Quantidade_Turmas,
MIN(CONVERT(nvarchar(4000),T.CODTURMA)) Turma_Exemplo
FROM dbo.STURMA T WHERE T.CODCOLIGADA=3
AND T.DTFINAL>=CONVERT(date,'20270101',112)
GROUP BY T.CODCOLIGADA,T.CODFILIAL,T.TIPOMEDIACAO
ORDER BY T.CODFILIAL,T.TIPOMEDIACAO;